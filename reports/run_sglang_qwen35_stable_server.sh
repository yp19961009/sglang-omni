  curl -fsS "http://127.0.0.1:$PORT/v1/models" >/tmp/qwen35_stable_models.json
  cat /tmp/qwen35_stable_models.json
  echo
  exit 0
fi

if [ "$FORCE_RESTART" = "1" ]; then
  stop_pids="$(collect_stable_stop_pids || true)"
  if [ -n "$stop_pids" ]; then
    echo "Stopping stable server process group on port $PORT: $stop_pids"
    kill $stop_pids || true
  fi
  for _ in $(seq 1 30); do
    remaining="$(collect_stable_stop_pids || true)"
    if [ -z "$remaining" ]; then
      break
    fi
    sleep 1
  done
  remaining="$(collect_stable_stop_pids || true)"
  if [ -n "$remaining" ]; then
    echo "Force stopping existing stable server process tree on port $PORT: $remaining"
    kill -9 $remaining || true
  fi
fi

