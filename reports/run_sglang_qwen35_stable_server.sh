collect_stable_stop_pids() {
  "$PYTHON_BIN" - "$PORT" "$CLEAN_ORPHAN_STAGE_WORKERS" <<'PY'
import os
import sys
from collections import defaultdict

port = int(sys.argv[1])
clean_orphans = sys.argv[2].lower() in {"1", "true", "yes", "y", "on"}


def read_cmdline(pid: int) -> str:
    try:
        raw = open(f"/proc/{pid}/cmdline", "rb").read()
    except OSError:
        return ""
    if not raw:
        try:
            return open(f"/proc/{pid}/comm", "r", encoding="utf-8").read().strip()
        except OSError:
            return ""
    return raw.replace(b"\x00", b" ").decode("utf-8", errors="replace").strip()


def read_ppid(pid: int) -> int:
    try:
        fields = open(f"/proc/{pid}/stat", "r", encoding="utf-8").read().split()
        return int(fields[3])
    except Exception:
        return 0


def listener_inodes(port: int) -> set[str]:
    wanted = f"{port:04X}"
    found: set[str] = set()
    for table in ("/proc/net/tcp", "/proc/net/tcp6"):
        try:
            rows = open(table, "r", encoding="utf-8").read().splitlines()[1:]
        except OSError:
            continue
        for row in rows:
            parts = row.split()
            if len(parts) < 10 or parts[3] != "0A":
                continue
            local = parts[1]
            if ":" not in local:
                continue
            _, hex_port = local.rsplit(":", 1)
            if hex_port.upper() == wanted:
                found.add(parts[9])
    return found


procs: dict[int, tuple[int, str]] = {}
children: dict[int, list[int]] = defaultdict(list)
for name in os.listdir("/proc"):
    if not name.isdigit():
        continue
    pid = int(name)
    ppid = read_ppid(pid)
    cmd = read_cmdline(pid)
    procs[pid] = (ppid, cmd)
    children[ppid].append(pid)

roots: set[int] = set()
port_forms = {f"--port {port}", f"--port={port}"}
for pid, (_, cmd) in procs.items():
    if "sglang_omni.cli" in cmd and "serve" in cmd and any(form in cmd for form in port_forms):
        roots.add(pid)

inodes = listener_inodes(port)
if inodes:
    for name in os.listdir("/proc"):
        if not name.isdigit():
            continue
        pid = int(name)
        fd_dir = f"/proc/{pid}/fd"
        try:
            fds = os.listdir(fd_dir)
        except OSError:
            continue
        for fd in fds:
            try:
                target = os.readlink(f"{fd_dir}/{fd}")
            except OSError:
                continue
            if target.startswith("socket:[") and target[8:-1] in inodes:
                roots.add(pid)
                break

to_stop = set(roots)
stack = list(roots)
while stack:
    pid = stack.pop()
    for child in children.get(pid, []):
        if child not in to_stop:
            to_stop.add(child)
            stack.append(child)

if clean_orphans:
    for pid, (ppid, cmd) in procs.items():
        if ppid != 1:
            continue
        if (
            "from multiprocessing.spawn import spawn_main" in cmd
            or "from multiprocessing.resource_tracker import main" in cmd
        ):
            to_stop.add(pid)

current = {os.getpid(), os.getppid()}
print(" ".join(str(pid) for pid in sorted(to_stop - current, reverse=True)))
PY
}

existing_pid="$(ps -eo pid,args | awk -v port="$PORT" '/sglang_omni.cli serve/ && index($0, "--port " port) && !/awk/ {print $1; exit}')"
if [ -n "$existing_pid" ] && [ "$FORCE_RESTART" != "1" ]; then
