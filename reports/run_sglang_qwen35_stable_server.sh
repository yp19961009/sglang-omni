for _ in range(30):
    sock = socket.socket()
    sock.settimeout(0.5)
    try:
        sock.connect(("127.0.0.1", port))
    except OSError:
        sock.close()
        break
    sock.close()
    time.sleep(1)
else:
    raise SystemExit(f"port {port} is still busy")
PY

