#!/usr/bin/env bash
set -euo pipefail

# Run from the server/container repo:
#   cd /myapp/sglang-omni
#   TRACE_CACHE=0 FORCE_RESTART=1 \
#     bash reports/run_sglang_qwen35_stable_server.sh
# See reports/README_qwen35_realtime_benchmark_20260701.md for the C1/C12
# benchmark commands and reference numbers.
# The script intentionally leaves QWEN35_MAMBA_MEDIA_BRANCH_CACHE unset by
# default. Qwen3.5 RTC requests with omitted cached visual payloads auto-disable
# that Mamba branch cache path because it can produce unstable text/audio under
# vLLM-style interleaved prefix/actual concurrency. Set the env var explicitly
# to force a value for debugging.
# Measured RTC actual requests keep Mamba tracking enabled so the final
# chunk updates the request-local SSM state used by decode. They still skip
# writing that actual state back into the radix cache. Prefix requests populate
# the reusable cache for the next realtime chunk.

