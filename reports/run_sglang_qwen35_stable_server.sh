    0|false|FALSE|no|NO)
      serve_args+=(
        --voice-type "$VOICE_TYPE_VALUE"
        --talker-gpu 1
        --code2wav-gpu 2
        --code2wav-model-path "$CODE2WAV_PATH"
        --code2wav-stream-chunk-size "$CODE2WAV_STREAM_CHUNK_SIZE_VALUE"
        --talker-partial-start-min-chunks "$TALKER_PARTIAL_START_MIN_CHUNKS_VALUE"
        --talker-cuda-graph on
        --talker-torch-compile on
        --talker-max-running-requests "$TALKER_MAX_RUNNING_REQUESTS_VALUE"
      )
      ;;
    *)
      echo "SGLANG_OMNI_THINKER_ONLY must be 1/0, true/false, or yes/no; got: $THINKER_ONLY" >&2
      exit 1
      ;;
  esac
  nohup "$PYTHON_BIN" -m sglang_omni.cli serve "${serve_args[@]}" \
    > "$RUN_DIR/server.log" 2>&1 &
  echo $! > "$RUN_DIR/server.pid"
)

echo "$PORT" > "$RUN_DIR/port.txt"
echo "RUN_DIR=$RUN_DIR"
echo "PID=$(cat "$RUN_DIR/server.pid")"

for i in $(seq 1 240); do
  if grep -q 'Using port .* instead' "$RUN_DIR/server.log" 2>/dev/null; then
    echo "Stable server fell back to a different port; expected $PORT" >&2
    tail -n 40 "$RUN_DIR/server.log" >&2
    exit 1
  fi
  if curl -fsS "http://127.0.0.1:$PORT/v1/models" >/tmp/qwen35_stable_models.json 2>/tmp/qwen35_stable_curl.err; then
    echo "ready_after=${i}s"
    cat /tmp/qwen35_stable_models.json
    echo
    case "$SERVER_WARMUP" in
      1|true|TRUE|yes|YES)
        warmup_text_args=()
        warmup_label="audioonly"
        case "$THINKER_ONLY" in
          1|true|TRUE|yes|YES)
            warmup_text_args=(--text-only)
            warmup_label="thinkeronly_audioonly"
            ;;
        esac
        WARMUP_DIR="$RUN_DIR/server_warmup_${warmup_label}_t${SERVER_WARMUP_TRUNK_SIZE}_$(date +%H%M%S)"
        echo "server_warmup=$warmup_label trunk=$SERVER_WARMUP_TRUNK_SIZE max_tokens=$SERVER_WARMUP_MAX_TOKENS out_dir=$WARMUP_DIR"
        PYTHONPATH=. "$PYTHON_BIN" benchmarks/eval/qwen35_omni_sglang_rtc_concurrency.py \
          --base-url "http://127.0.0.1:${PORT}" \
          --model qwen3_5-omni \
          --output-dir "$WARMUP_DIR" \
          --trunk-size "$SERVER_WARMUP_TRUNK_SIZE" \
          --concurrency 1 \
          --total-samples 1 \
          --stagger-ms 0 \
          --sil-offset 0 \
          --question-offset 0 \
          --audio-only \
          --temperature 1.0 \
          --voice "$VOICE_TYPE_VALUE" \
          --prefix-max-tokens 2 \
          --max-tokens "$SERVER_WARMUP_MAX_TOKENS" \
          "${warmup_text_args[@]}" \
          > "$WARMUP_DIR.log"
        echo "server_warmup_done=$WARMUP_DIR"
        ;;
      0|false|FALSE|no|NO)
        echo "server_warmup=disabled"
        ;;
      *)
        echo "SGLANG_OMNI_SERVER_WARMUP must be 1/0, true/false, or yes/no; got: $SERVER_WARMUP" >&2
        exit 1
        ;;
    esac
    exit 0
  fi
  if ! kill -0 "$(cat "$RUN_DIR/server.pid")" 2>/dev/null; then
    echo "Stable server exited during startup" >&2
    tail -n 160 "$RUN_DIR/server.log" >&2
    exit 1
  fi
  if [ $((i % 30)) -eq 0 ]; then
    echo "waiting ${i}s"
    tail -n 12 "$RUN_DIR/server.log" || true
  fi
  sleep 1
done

echo "Stable server did not become ready within timeout" >&2
tail -n 200 "$RUN_DIR/server.log" >&2
exit 1
